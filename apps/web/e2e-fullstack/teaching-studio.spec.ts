test('author, publish, answer and submit an anonymous formative assessment', async ({ page, browser }) => {
  await page.getByRole('button', { name: 'Teaching Studio', exact: true }).click()
  await page.getByRole('button', { name: 'New assessment', exact: true }).click()
  await page.getByRole('button', { name: 'Create assessment', exact: true }).click()
  await page.getByRole('button', { name: 'Upgrade to sections', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Question type for section 1', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Assessment name', exact: true }).fill('QA formative journey')
  await page.getByRole('combobox', { name: 'Question type for section 1', exact: true }).selectOption('multiple-choice')
  await page.getByRole('button', { name: 'Add selected question to section 1', exact: true }).click()
  await page.getByRole('textbox', { name: 'Question', exact: true }).fill('Choose the synthetic QA answer')
  await page.getByRole('textbox', { name: 'Option 1', exact: true }).fill('Synthetic A')
  await page.getByRole('textbox', { name: 'Option 2', exact: true }).fill('Synthetic B')
  await page.getByLabel('Correct option 1', { exact: true }).check()
  await expect(page.getByText('All changes saved', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Assessment name', exact: true })).toHaveValue('QA formative journey')
  await page.getByRole('button', { name: 'Publish', exact: true }).click()
  const publish = page.getByRole('dialog', { name: 'Publish assessment', exact: true })
  await publish.getByRole('combobox', { name: 'Mode', exact: true }).selectOption('formative')
  for (const checkbox of await publish.getByRole('checkbox').all()) {
    if (await checkbox.isChecked() && await checkbox.getAttribute('type') === 'checkbox'
      && await checkbox.evaluate((element) => Boolean(element.closest('fieldset')))) await checkbox.uncheck()
  }
  const publishing = page.waitForResponse((response) => response.request().method() === 'POST' && response.url().includes('/publish'))
  await publish.getByRole('button', { name: 'Publish assignment', exact: true }).click()
  const publicationResult = await publishing
  expect(publicationResult.ok(), await publicationResult.text()).toBe(true)
  await publish.getByRole('button', { name: 'Open responses', exact: true }).click()
  await expect(publish.getByText('Accepting responses. You can share this link.', { exact: true })).toBeVisible()
  const href = await publish.locator('a[href*="/assessment/"]').last().getAttribute('href')
  expect(href).toBeTruthy()
  const learner = await browser.newContext({ timezoneId: 'Asia/Bangkok' })
  try {
    const student = await learner.newPage()
    await student.goto(href!)
    await student.getByRole('button', { name: 'Continue anonymously', exact: true }).click()
    await student.getByRole('radio', { name: 'Synthetic A', exact: true }).check()
    await expect(student.getByText(/(?:59:\d\d|60:00) · Saved$/)).toBeVisible()
    await student.reload()
    await expect(student.getByRole('radio', { name: 'Synthetic A', exact: true })).toBeChecked()
    await student.getByRole('button', { name: 'Submit assessment', exact: true }).click()
    await student.getByRole('button', { name: 'Submit assessment', exact: true }).click()
    await expect(student.getByRole('heading', { name: 'Assessment submitted', exact: true })).toBeVisible()
  } finally { await learner.close() }
  await publish.getByRole('button', { name: 'Close publish settings', exact: true }).click()
  await page.getByRole('tab', { name: 'Responses', exact: true }).click()
  await expect(page.getByText('1 of 1 learners completed', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('1 of 1 learners completed', { exact: true })).toBeVisible()
  await page.getByRole('switch', { name: 'Accepting responses', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'Accepting responses', exact: true })).toHaveAttribute('aria-checked', 'false')
})
